# 오버행 판정 임계각(도).
#   이 각도보다 심하게 '아래를 보는' 면은 서포트가 필요하다고 본다.
#   보통 FDM 프린터는 45°까지는 서포트 없이 출력되므로 기본값 45.
THRESHOLD_DEG = 45.0

# 하드웨어가 허용하는 최대 원뿔 각도(도). 각도 탐색은 여기까지만 한다.
#   · 3축 프린터만 사용   → 25 정도 (노즐-출력물 간섭)
#   · Open5x 틸트 한계(조사 확인, 2026-07): Prusa판은 공식 스펙 없음,
#     Voron판 펌웨어 제한 ±110°, 논문 시연 90°. → 원뿔 44°는 전부 여유.
#     단 실기별 간섭은 기계에서 확인 (conical/open5x.py 의 MachineProfile 참고).
#   ⚠ 하드코딩하지 말고 반드시 이 설정값을 쓸 것.
MAX_ANGLE_DEG = 44

# 각도 탐색 간격(도). 2면 0,2,4,...44 를 훑는다. 작을수록 촘촘하지만 느리다.
ANGLE_STEP = 2

# 가변각 블렌드에서 허용하는 '층간격 배율' 상한.
#   변환공간에서 층고 간격으로 자른 레이어가 실공간에서는 배율 m = 1 − c·r·s 만큼
#   벌어지거나(팽창) 겹친다(압축). m 이 크면 레이어 사이가 떠서 지지가 사라진다.
#   이 값은 툴패스 검사기가 실측으로 잡아낸 결함에서 나왔다: 구 밴드2(36°→0°,
#   블렌드 0.5mm)에서 m=15배 → 미지지 25.5% (docs/verification.md).
#   1.5 = "레이어가 층고의 1.5배보다 더 벌어지지 않는다" (검사기 A 의 지지 판정 창과 동일).
#   ⚠ 하드코딩하지 말고 반드시 이 설정값을 쓸 것.
MAX_SPACING_FACTOR = 1.5

# 평가함수 J 의 '블렌드 비용' 가중치.
#   각도를 바꾸려면 블렌드가 필요하고, 그 구간은 층이 최대 MAX_SPACING_FACTOR 배까지
#   벌어진다. 그런데 해석식 판정(analytic)은 면을 '그 높이의 국소 원뿔각'과만 비교해서
#   이 팽창을 아예 못 본다 — 구 밴드2를 서포트 0.5%로 예측하지만 툴패스로는 균일각에
#   진다. 그래서 J 에 명시적으로 비용을 넣는다:
#       blend_cost = Σ (블렌드 구간의 표면적 %) × (m−1)/(limit−1)
#   (m−1)/(limit−1) = '허용된 층간격 여유를 얼마나 썼는가' (0~1).
#   k_blend=1 이면 "여유를 다 쓴 블렌드가 표면적 1%를 덮는 비용 = 서포트 1%p".
#   ⚠⚠ 2026-09-22 정정: 이 선형 가중은 **항등이라 작동한 적이 없다.** 계획기가
#      블렌드 폭을 층간격 제약의 최소값으로 잡아 m=limit 이 정확히 물리므로
#      (m−1)/(limit−1) ≡ 1 이다 (선택 프로필 16/16). 실제로 남는 비용은
#      Σ(블렌드 구간 표면적 %) 뿐이고, 블렌드 폭이 r_b·|Δtanθ|/(limit−1) 이므로
#      이 항은 **반경으로 가중한 각도 변화량**을 벌하는 정규화항이다.
#      따라서 아래 k_blend 는 **물리 계수가 아니라 정규화 세기**다.
#      (analyze_blend_cost.py / tests/test_blend_cost_identity.py 가 고정)
#
#   2026-09-19: 0.5 → 0.1 로 낮췄다. 0.5 는 analyze_blend_k.py 의 창(0.1~1.5)
#   한가운데였는데, 그 창의 '정답'("구=균일, 램프=부위별")이 **오염된 지표**로
#   정의돼 있었다 — 페리미터 미지지에 오버행 아닌 몫이 섞여 구 밴드2가 4.93%로
#   보였고(진짜 오버행은 0.48%p), 그래서 이 항이 필요해 보였다.
#   진짜 오버행으로 다시 재니 0.5 는 과하다:
#       램프 밴드2  k_blend=0.5 → 1.12%p / 16.3°   (각도 [24, 4])
#                   k_blend=0.1 → 0.33%p / 18.6°   (각도 [30, 0])  ← 3.4배 낫다
#       구   밴드2  0.1 과 0.5 가 동일 (둘 다 균일 28° 로 수렴)
#   0 으로 두면 여전히 병리적이다 — 구에서 [36°, −44°] 에 블렌드 19.9mm 를 골라
#   오버행 1.81%p 가 된다. 그래서 항은 남기되 작게 둔다.
#   ⚠ 남은 의문: 선택에 블렌드 비용을 아예 안 넣는 select_banded 가 구에서
#     0.48%p / 18.9° 로 균일(0.51%p / 28.0°)을 두 축 모두에서 이긴다.
#     "구에서는 균일이 정답"이라는 전제 자체를 다시 봐야 한다 → docs/verification.md
#
#   2026-09-22 (analyze_rho_threshold.py): 이 값이 **판정 문턱을 직접 정한다.**
#   밴드 승패를 가르는 비용/이득 비 ρ 의 문턱이 `ρ* ≈ 0.8/k_blend` 다(실측:
#   k_blend 0.05→0.1 에서 ρ* 18.88→7.79, 곱 0.94/0.78). 즉 "밴드가 이기는 조건"은
#   순수 기하 조건이 아니라 **여기 적힌 수가 정하는 것**이다.
#   ⚠⚠ 그리고 **전역값 하나로는 안 맞는다**: 0.1 → 0.05 로 낮추면
#       · 허리 r=5 가 1.062 → **0.199**%p (균일 0.956 대비 4.8배) — 0.1 은 과보수적
#       · 구는 0.515 → **2.159**%p (균일보다 4.2배 나쁨) — k_blend 가 막으려던 병리
#     둘을 가르는 양은 이미 있다(구 ρ=51.4 vs 허리 r=5 ρ=8.1).
#     → 제안: k_blend 가 J 안에서 암묵적으로 밴딩 여부를 정하게 두지 말고 ρ 로
#       밴딩 시도를 게이트할 것. ⚠ 미구현·미검증 (docs/verification.md 2026-09-22)
BLEND_COST_K = 0.1

# 밴드 경계를 반경이 작은 높이로 옮겨볼 수 있는 최대 거리 = (모델 높이) × 이 비율.
#   블렌드 폭은 그 높이의 반경에 비례하므로, '허리'가 있는 모델은 경계를 조금만
#   옮겨도 필요한 블렌드가 크게 줄어든다. 0 = 경계 고정(옮기지 않음).
#   ⚠ '밴드 높이' 기준이었다가 '모델 높이' 기준으로 바꿨다(실측): 밴드 높이 기준이면
#     N이 커질수록 예산이 줄어(h/N) 밴드를 더 잘게 나눌수록 허리에 못 닿는다.
#     그래서 J가 N에 대해 단조가 아니었다(램프 N=2: 3.30 > N=4: 2.82).
#     '가장 가까운 허리까지의 거리'는 몇 개로 나눴는지와 무관한 모델의 성질이다.
#     크게 잡아도 안전하다 — 이동 비용(폭+거리)이 알아서 제자리를 지킨다.
BLEND_SHIFT_RATIO = 0.25

# 평가함수 J = (서포트 감소) − k×각도 의 기본 각도 비용 가중치.
#   analyze_k 의 자연 스케일 분석(서포트 곡선 기울기 %p/°) 참조 — 모델별 재검토 대상.
#   서포트만 최소화하면 항상 최대각이 선택되는 '최소화의 함정'을 막는 값.
DEFAULT_K = 0.2


# ─────────────────────────────────────────────────────────────
# 각도 관례 — 실제 슬라이서와의 정합 (발표/논문 인용용)
# ─────────────────────────────────────────────────────────────
# 이 코드의 오버행 각도 정의: overhang_angle = arcsin(-n_z)
#   0° = 수직 벽,  90° = 수평 천장,  임계각을 '초과'하면 서포트 필요.
# 실제 슬라이서 관례와의 대응(오픈소스 소스코드 기준으로 확인):
#   · Cura "Support Overhang Angle"  : 완전히 동일. '수직 기준' 각도이고
#       임계각 '초과' 시 서포트. Cura 기본값 50°(과거 45°). → 우리와 1:1.
#   · PrusaSlicer / SuperSlicer / OrcaSlicer : '여집합'.
#       이들은 '수평 기준' 경사각을 쓰고, 경사각이 임계각 '미만'일 때 서포트.
#       따라서  prusa_threshold ≈ 90 − (우리 임계각).  Orca 기본값 30°.
#   (출처: CuraEngine src/support.cpp, PrusaSlicer PrintConfig.cpp /
#          Support/SupportMaterial.cpp, OrcaSlicer PrintConfig.cpp. docs/slicer_conventions.md 참고)

def ours_to_prusa(threshold_deg):
    """우리(=Cura) 임계각을 PrusaSlicer/Orca 관례(수평 기준)로 변환."""
    return 90.0 - threshold_deg


def prusa_to_ours(prusa_threshold_deg):
    """PrusaSlicer/Orca 관례(수평 기준) 임계각을 우리(=Cura) 관례로 변환."""
    return 90.0 - prusa_threshold_deg
